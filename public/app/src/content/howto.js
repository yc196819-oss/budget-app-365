// Where "פרופיל" is on this screen: a phone and a computer show it in
// different places.
export function profileHint(answer, wide = typeof matchMedia === 'function' && matchMedia('(min-width: 1024px)').matches) {
  if (!/פרופיל/.test(String(answer || ''))) return '';
  return wide ? '\n(במחשב: הפרופיל בכפתור עם השם בתחתית התפריט שבצד.)' : '\n(בטלפון: הפרופיל בעיגול עם האותיות בפינה העליונה.)';
}
