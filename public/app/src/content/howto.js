// A "how do I…" question: asks about doing something in the app, not about
// the money itself.
const INTENT = ['איך', 'איפה', 'היכן', 'כיצד', 'אפשר', 'ניתן', 'רוצה', 'צריך', 'מה עושים', 'לאן', 'מאיפה', 'מה זה', 'מה זו', 'יש דרך', 'יש אפשרות', 'אין אפשרות', 'לא מצליח', 'לא מצליחה', 'לא מוצא', 'לא מוצאת', 'מה היועץ', 'יש קיצורי'];

const norm = (s) => ' ' + String(s || '').toLowerCase().replace(/[֑-ׇ]/g, '').replace(/[?!.,;:()"'״׳\-–—]/g, ' ').replace(/\s+/g, ' ').trim() + ' ';
// A key matches at the start of a word, after up to two of the letters
// Hebrew joins to a word (ו ה ב ל מ ש כ), so "מהפירוט" has "פירוט". Keys
// must be long enough that a joined letter cannot fake them (no "סף":
// "כסף" is כ + סף).
const esc = (k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const has = (text, stem) => new RegExp('(^|\\s)[והבלמשכ]{0,2}' + esc(norm(stem).trim())).test(text);

// The entry that answers the question, or null. Every group of an entry
// must match; among several, the one with the most (and longest) matches.
export function matchHowto(question) {
  const text = norm(question);
  if (text.trim().length < 4 || text.length > 160) return null;
  if (!INTENT.some((w) => has(text, w))) return null;
  let best = null;
  for (const e of HOWTO) {
    let score = 0;
    let all = true;
    for (const group of e.keys) {
      const hits = group.filter((k) => has(text, k));
      if (!hits.length) { all = false; break; }
      score += 10 + Math.max(...hits.map((k) => k.length));
    }
    if (all && (!best || score > best.score)) best = { entry: e, score };
  }
  return best ? best.entry : null;
}

